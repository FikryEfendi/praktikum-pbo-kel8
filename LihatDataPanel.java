    private void hapusButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_hapusButtonActionPerformed
        // TODO add your handling code here:
            if (barisTerpilih == -1) {
            JOptionPane.showMessageDialog(this, 
                "Silahkan pilih data yang ingin dihapus");
        } else {
            String nama = daftarMahasiswaTable.getValueAt(barisTerpilih, 1).toString();

            int konfirmasi = JOptionPane.showConfirmDialog(this, 
                "Apakah Anda yakin ingin menghapus data mahasiswa:\n" + nama + "?", 
                "Konfirmasi Hapus",JOptionPane.YES_NO_OPTION);

            if (konfirmasi == JOptionPane.YES_OPTION) {
                Mahasiswa.mahasiswas.remove(barisTerpilih);                
                loadData();
                
                barisTerpilih = -1;
                JOptionPane.showMessageDialog(this,"Data mahasiswa berhasil dihapus!");
            }
        }
    }//GEN-LAST:event_hapusButtonActionPerformed


