    private void updateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateButtonActionPerformed
        // TODO add your handling code here:
        if (barisTerpilih == -1){
            JOptionPane.showMessageDialog(this, "Silahkan pilih data yang ingin di-update");
        } 
        else {
            String nama = daftarMahasiswaTable.getValueAt(barisTerpilih, 1).toString();
            String nim = daftarMahasiswaTable.getValueAt(barisTerpilih, 2).toString();
            String prodi = daftarMahasiswaTable.getValueAt(barisTerpilih, 3).toString();
            String jenisKelamin = daftarMahasiswaTable.getValueAt(barisTerpilih, 4).toString();
            String status = daftarMahasiswaTable.getValueAt(barisTerpilih, 5).toString();
            
            TambahDataPanel tambahPanel = new TambahDataPanel(mainFrame, barisTerpilih);
            tambahPanel.setModeUpdate(nama, nim, prodi, jenisKelamin, status);
            
            mainFrame.changeMainPanel(tambahPanel);
        }
    }
    

