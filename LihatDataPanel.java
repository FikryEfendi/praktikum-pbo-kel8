    private void loadData(){
        String[] column = {"No.","Nama", "NIM", "Prodi", "Jenis Kelamin", 
            "Status"};
        DefaultTableModel table = new DefaultTableModel(null, column){
          @Override  
          public boolean isCellEditable(int row, int col){
              return false;
          }
        };
        
        int i = 1;        
        for (Mahasiswa mhs : Mahasiswa.mahasiswas) {
            
            table.addRow(new String[]{String.valueOf(i), mhs.getNama(), 
                mhs.getNim(), mhs.getProdi(), mhs.getJenisKelamin(),
            mhs.getIsActive() ? "Aktif" : "Tidak Aktif"});
            i++;
        }        
        daftarMahasiswaTable.setModel(table);
    }
